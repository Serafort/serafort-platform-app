#!/usr/bin/env node
/**
 * Backend Route Snapshot Synchronization Script
 *
 * Captures the AdonisJS backend's real route table (`node ace list:routes`) into
 * a JSON fixture consumed by `endpoints.routes.test.ts`. That test asserts every
 * path in the `API_ENDPOINTS` registry resolves to a route the backend actually
 * serves, so a route removed or renamed on the backend fails the frontend suite
 * instead of turning into a silent 404 in a shipped auth flow.
 *
 * Run after any backend routing change:
 *   node scripts/sync-route-snapshot.mjs
 */

import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const ROOT_DIR = path.resolve(__dirname, '../..')
const BACKEND_DIR = path.resolve(ROOT_DIR, 'Authentication')
const SNAPSHOT_PATH = path.resolve(
  ROOT_DIR,
  'boilerplate/packages/api-contracts/src/__fixtures__/backend-routes.json'
)

console.log(`[sync-route-snapshot] Reading backend routes from: ${BACKEND_DIR}`)

if (!fs.existsSync(BACKEND_DIR)) {
  console.error(`[sync-route-snapshot] Backend directory not found: ${BACKEND_DIR}`)
  process.exit(1)
}

/**
 * `list:routes --json` writes the route table to stdout, but the app's boot
 * sequence and shutdown hooks log around it (event listeners, queue provider,
 * monitoring service). Slice out the top-level JSON array rather than trying to
 * silence the logger, which would mean booting the app differently than usual.
 */
function extractJsonArray(raw) {
  const start = raw.indexOf('\n[\n') === -1 ? raw.indexOf('[\n') : raw.indexOf('\n[\n') + 1
  const end = raw.lastIndexOf('\n]')
  if (start === -1 || end === -1 || end < start) {
    throw new Error('could not locate the JSON array in `list:routes --json` output')
  }
  return JSON.parse(raw.slice(start, end + 2))
}

let raw
try {
  raw = execFileSync('node', ['ace', 'list:routes', '--json'], {
    cwd: BACKEND_DIR,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  })
} catch (error) {
  console.error(`[sync-route-snapshot] \`node ace list:routes\` failed: ${error.message}`)
  process.exit(1)
}

const domains = extractJsonArray(raw)

// Flatten to the three fields the drift guard needs. HEAD is dropped: Adonis
// derives it from every GET, so keeping it would double the snapshot for no
// added coverage.
const routes = []
for (const domain of domains) {
  for (const route of domain.routes ?? []) {
    for (const method of route.methods ?? []) {
      if (method === 'HEAD') continue
      routes.push({ method, pattern: route.pattern, name: route.name || '' })
    }
  }
}

routes.sort((a, b) => a.pattern.localeCompare(b.pattern) || a.method.localeCompare(b.method))

const snapshot = {
  _comment:
    'Generated by scripts/sync-route-snapshot.mjs from `node ace list:routes --json`. DO NOT EDIT DIRECTLY.',
  generatedFrom: 'Authentication/start/routes.ts',
  routeCount: routes.length,
  routes,
}

fs.mkdirSync(path.dirname(SNAPSHOT_PATH), { recursive: true })
fs.writeFileSync(SNAPSHOT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`, 'utf8')

console.log(`[sync-route-snapshot] Wrote ${routes.length} routes to: ${SNAPSHOT_PATH}`)
